"""Generate the Windows version resource for TurboWhisper.exe at build time.

The version is read from pyproject.toml (the single source of truth), so the
exe never carries a stale hardcoded version. Called from the PyInstaller spec
files:

    import sys
    sys.path.insert(0, SPECPATH)
    from build_version_info import generate_version_info

    exe = EXE(..., version=generate_version_info())
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def read_version() -> str:
    """Read the project version from pyproject.toml."""
    pyproject = ROOT / "pyproject.toml"
    text = pyproject.read_text(encoding="utf-8")
    m = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
    if not m:
        raise RuntimeError(f"Cannot find 'version = \"...\"' in {pyproject}")
    return m.group(1)


def version_tuple(ver: str) -> tuple[int, int, int, int]:
    """Convert '1.2.3' / '1.2.3-rc1' into a 4-int tuple (1, 2, 3, 0)."""
    nums: list[int] = []
    for part in re.split(r"[.\-+]", ver)[:4]:
        try:
            nums.append(int(part))
        except ValueError:
            nums.append(0)
    while len(nums) < 4:
        nums.append(0)
    return tuple(nums[:4])  # type: ignore[return-value]


_TEMPLATE = """\
# UTF-8
# AUTO-GENERATED by build_version_info.py at build time -- do not edit.
# Version {ver} is read from pyproject.toml.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vt},
    prodvers={vt},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', 'KnowAll AI'),
        StringStruct('FileDescription', 'Turbo Whisper - voice dictation and transcription'),
        StringStruct('FileVersion', '{ver4}'),
        StringStruct('InternalName', 'TurboWhisper'),
        StringStruct('LegalCopyright', 'Copyright (c) 2026 KnowAll AI. MIT License.'),
        StringStruct('OriginalFilename', 'TurboWhisper.exe'),
        StringStruct('ProductName', 'Turbo Whisper'),
        StringStruct('ProductVersion', '{ver4}')])
      ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def generate_version_info() -> str:
    """Write the VSVersionInfo file and return its path for EXE(version=...)."""
    ver = read_version()
    vt = version_tuple(ver)
    ver4 = ".".join(str(n) for n in vt)
    out = ROOT / "build" / "version_info_generated.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(_TEMPLATE.format(ver=ver, vt=vt, ver4=ver4), encoding="utf-8")
    print(f"build_version_info: version {ver} -> {out}")
    return str(out)


if __name__ == "__main__":
    generate_version_info()
